def _latex_escape_label(label):
    label = label.replace('TcpCubic', 'TCP')
    label = label.replace('TcpNewReno', 'TCP')
    label = label.replace('#', '\\#')  # Escape characters for LaTeX
    return label


def latex_plot_header(label: str):
    # Print the full command line with all args used to generate the plot
    print(f"\n% {label} (Generated by '{os.path.basename(__file__)} {" ".join(sys.argv[1:])}' at {datetime.datetime.now().strftime('%Y-%m-%d %H:%M')})")


def latex_plot(x: list, y: list, label: str, header: str, sharp=False):
    if not args.latex:
        return
    latex_plot_header(f"{label} - {header}")
    coordinates = ' '.join([f'({round(xi, 2)},{round(yi, 2)})' for xi, yi in zip(x, y) if xi is not None and yi is not None])
    extra_args = ", sharp plot" if sharp else ""
    print(f"\\addplot+[label={_latex_escape_label(label)}{extra_args}] coordinates {{{coordinates}}};")


def latex_boxplot(data, label):
    if not args.latex:
        return
    data = np.array(data)
    median = np.median(data)
    upper_quartile = np.percentile(data, 75)
    lower_quartile = np.percentile(data, 25)

    # https://en.wikipedia.org/wiki/Box_plot#Whiskers
    iqr = upper_quartile - lower_quartile
    upper_whisker = data[data <= upper_quartile + 1.5 * iqr].max()
    lower_whisker = data[data >= lower_quartile - 1.5 * iqr].min()

    latex_plot_header(label)
    print(f"\\addplot+[\n"
          f"    fill,\n"
          f"    fill opacity=0.7,\n"
          f"    draw=linecolor_before,\n"
          f"    thick,\n"
          f"    boxplot prepared={{\n"
          f"        median={median},\n"
          f"        upper quartile={upper_quartile},\n"
          f"        lower quartile={lower_quartile},\n"
          f"        upper whisker={upper_whisker},\n"
          f"        lower whisker={lower_whisker},\n"
          f"    }},\n"
          f"] coordinates {{}};")


def latex_plot_errorbar(x, y, yerr, label):
    if not args.latex:
        return

    latex_plot_header(label)
    print("\\addplot+[error bars/.cd, y dir=both, y explicit] coordinates {")
    for xi, yi, yerri in zip(x, y, yerr):
        print(f"({xi},{yi}) +- (0,{yerri})")
    print("};")


