        #         # If --avg was used, we already average the values in the individual results parsing
        #         average_num = 1
        #     else:
        #         average_num = 6

        #     if args.loss:
        #         losses = app['loss']
        #         averaged_losses = [np.mean(losses[i:i+average_num]) for i in range(0, len(losses), average_num)]
