def compute_vmaf_score(latency: float, jitter: float, loss: float, sendrate: float):
    """
    Compute the VMAF score based on the given QoE metrics

    Parameters:
    - latency: Latency value in ms
    - jitter: Jitter value in ms
    - loss: Packet loss percentage
    - sendrate: Bandwidth in DATARATE_UNIT

    Returns:
    - vmaf_score: Computed VMAF score
    """

    """
    VMAF (0-100) scores for loss (in %) with 50% correlation, Threema low bandwidth profile:
    0%: 59.83, 10%: 57.96, 15%: 57.53, 20%: 58.53, 30%: 53.55, 35%: 6.82, 40%: 6.13

    VMAF scores (0-100) for varying levels of uncorrelated, normally distributed jitter (in ms) with 150 ms added network latency under the Threema high bandwidth profile:
    0ms: 68.34, 5ms: 64.91, 10ms: 62.58, 15ms: 46.91, 20ms: 32.78, 30ms: 5.545542

    VMAF scores (0-100) for bandwidth in Mbps, with Threema Balanced Setting defaulting to the Low Bandwidth Profile in a Cellular Network:
    0.2Mbps: 16.76, 0.3Mbps: 37.07, 0.5Mbps: 48.75, 1Mbps: 58.49, 2Mbps: 59.30, 3Mbps: 59.51
    """

    # Convert sendrate to Mbps
    if DATARATE_UNIT == 'Mbps':
        Mbps = sendrate
    elif DATARATE_UNIT == 'MB/s':
        Mbps = sendrate * 8
    else:
        raise ValueError(f"Unknown DATARATE_UNIT: {DATARATE_UNIT}")

    loss_values = [0, 10, 15, 20, 30, 35, 40]
    loss_scores = [59.83, 57.96, 57.53, 58.53, 53.55, 6.82, 6.13]

    jitter_values = [0, 5, 10, 15, 20, 30]
    jitter_scores = [68.34, 64.91, 62.58, 46.91, 32.78, 5.545542]

    bandwidth_values = [0.2, 0.3, 0.5, 1, 2, 3]
    bandwidth_scores = [16.76, 37.07, 48.75, 58.49, 59.30, 59.51]

    # To scale the bandwidth_values
    # bandwidth_values = [x * 4 for x in bandwidth_values]

    # Interpolate
    loss_score = np.interp(loss, loss_values, loss_scores)
    jitter_score = np.interp(jitter, jitter_values, jitter_scores)
    bandwidth_score = np.interp(Mbps, bandwidth_values, bandwidth_scores)

    vmaf_score = np.mean([loss_score, jitter_score, bandwidth_score])

    return vmaf_score


def parse_simulation_results(file, inputs: dict) -> dict:
    """
    Parse the results from the simulation output file

    Returns a dictionary containing the parsed results

    This also requires the inputs file to get the traffic types and the
    simulation settings like time slot information, which the simulation itself
    is unaware of.
    """
    apps = []
    while (True):
        line = file.readline().strip()
        if "End Apps evaluation" in line:
            break
        elif "Host at" in line:
            host_tokens = line.split(' ')
            host = host_tokens[2]
        elif "{" in line:
            app = json.loads(line)
            app['host'] = host
            # print(f"Found results for host {host} app {
            #       app['app_id']} type {app['app_type']}")

            if 'states' not in app or app['states'] is None:
                print(f"    No states found for app {app['app_id']}")
                print(json.dumps(app, indent=4))
                continue

            # Select only states from args.start_time onwards
            app['states'] = [state for state in app['states'] if state['time'] >= args.start_time * 1000]

            # Remove startup from time and convert to seconds
            app['time'] = [state['time'] / 1000 -
                           args.start_time for state in app['states']]

            # Convert loss to percentage
            app['loss'] = [state['loss'] * 100 for state in app['states']]

            app['sendrate'] = [DATARATE_UNIT_FACTOR * state['sendrate'] for state in app['states']]

            # If bottleneck share is available, multiply by DATARATE_UNIT_FACTOR
            if 'bottleneck_share' in app['states'][0]:
                app['bottleneck_share'] = [state['bottleneck_share'] * DATARATE_UNIT_FACTOR for state in app['states']]

            # Optional metrics for path transitions
            if 'in_transition' in app['states'][0]:
                app['oldrate'] = []
                app['newrate'] = []
                app['time_transition'] = []
                for i, state in enumerate(app['states']):
                    if state['in_transition']:
                        app['oldrate'].append(state['oldrate'] * DATARATE_UNIT_FACTOR)
                        app['newrate'].append(state['newrate'] * DATARATE_UNIT_FACTOR)
                        app['time_transition'].append(app['time'][i])
                    else:
                        app['oldrate'].append(None)
                        app['newrate'].append(None)
                        app['time_transition'].append(None)

            # For ever other field in states, generate a list of values
            for field in app['states'][0]:
                if field not in app:
                    app[field] = _get_state_attr_list(app, field)

            # If target app, compute VMAF score
            if 'jitter' in app:
                app['vmaf_score'] = []
                for state in app['states']:
                    # Compute VMAF score
                    score = compute_vmaf_score(
                        state['latency'], state['jitter'], state['loss'] * 100, state['sendrate'])
                    app['vmaf_score'].append(score)

            # Fallback to jitter as standard deviation of latency deltas if not already available
            if 'jitter' not in app:
                # Compute jitter from the latencies
                deltas = np.diff(app['latency'])
                app['jitter'] = np.std(deltas)

            if np.mean(app['jitter']) > 10:
                print(f"App {app['app_id']} {app['app_type']} has high average jitter: {np.mean(app['jitter'])}")

            if args.avg > 1:
                for field in ['sendrate', 'loss', 'latency', 'jitter']:
                    # Average args.avg many values together
                    app[field] = [np.mean(app[field][i:i + args.avg])
                                  for i in range(0, len(app[field]), args.avg)]
                app['time'] = [app['time'][i] for i in range(0, len(app['time']), args.avg)]
                app['active_path'] = [app['active_path'][i] for i in range(0, len(app['active_path']), args.avg)]
                if 'bottleneck_share' in app:
                    app['bottleneck_share'] = [app['bottleneck_share'][i] for i in range(0, len(app['bottleneck_share']), args.avg)]

            if not 'name' in app:
                app['name'] = f"{app['app_type']}#{app['app_id']} "

            app['total_running_time'] = app['time'][-1] - app['time'][0]
            app['average_bandwidth'] = app['bytes_received'] / app['total_running_time'] * DATARATE_UNIT_FACTOR / 1e6

            app['bytes_lost'] = app['bytes_sent'] - app['bytes_received']
            if app['bytes_sent'] > 0:
                app['total_loss_percentage'] = app['bytes_lost'] / app['bytes_sent'] * 100
                # if app['total_loss_percentage'] > 90:
                #     print(f"App {app['name']} {app['app_type']} has high loss: {app['total_loss_percentage']}")
            else:
                app['total_loss_percentage'] = 0
                print(f"App {app['name']} has 0 bytes sent")
            if app['total_loss_percentage'] < 0:
                app['total_loss_percentage'] = 0
                # print(f"App {app['name']} has negative loss: {app['total_loss_percentage']}")

            apps.append(app)

    if len(apps) == 0:
        print(f"No app results found in {file.name}")
        return {}
    else:
        print(f"Loaded {len(apps):2} apps from {file.name}")

    # Pre-process a dict with total sendrate and number of active apps at any point in time
    timestamps = {}
    for app in apps:
        for state in app['states']:
            t = state['time']
            if t not in timestamps:
                timestamps[t] = {'active_apps': 0, 'total_sendrate': 0}

            timestamps[t]['active_apps'] += 1
            timestamps[t]['total_sendrate'] += state['sendrate']

    median_total_sendrate = np.median([r['total_sendrate'] for r in timestamps.values()])

    timestamps = {t / 1000 - args.start_time: r for t, r in timestamps.items()}
    timestamps = dict(sorted(timestamps.items()))

    settings = {}
    time_slots = {}

    if inputs is not None and 'applications' in inputs:
        # Copy traffic type (target or background) from input file, because
        # simulation is unaware of it, and so is its output
        for app, app_input in zip(
                sorted(apps, key=lambda x: x['app_id']),
                inputs['applications']
        ):
            if app['app_id'] != app_input['app_id']:
                print(f"App ID mismatch: {app['app_id']} vs {app_input['app_id']}")
                exit(1)

            if 'traffic_type' in app_input:
                app['traffic_type'] = app_input['traffic_type']

        if 'settings' in inputs:
            settings = inputs['settings']

            time_slots = {}
            for t, r in timestamps.items():
                slot = int(t // settings['slot_size'])
                if slot not in time_slots:
                    time_slots[slot] = {}
                if 'total_sendrates' not in time_slots[slot]:
                    time_slots[slot]['total_sendrates'] = []
                time_slots[slot]['total_sendrates'].append(r['total_sendrate'])

            for slot, results in time_slots.items():
                time_slots[slot]['median_total_sendrate'] = np.median(results['total_sendrates'])

            # For each app, sum up the average sendrate in every time slot
            for app in apps:
                for t, s in zip(app['time'], app['sendrate']):
                    slot = int(t // settings['slot_size'])
                    if 'sendrate' not in time_slots[slot]:
                        time_slots[slot]['sendrate'] = []
                    time_slots[slot]['sendrate'].append(s)
            for slot, results in time_slots.items():
                time_slots[slot]['median_sendrate'] = np.median(results['sendrate'])
                time_slots[slot]['mean_sendrate'] = np.mean(results['sendrate'])
                time_slots[slot]['min_sendrate'] = np.min(results['sendrate'])
    else:
        print("Some processing skipped due to missing inputs file")

    # Erase the states after processing to save memory
    for app in apps:
        del app['states']

    scenario = {
        'apps': apps,
        'timestamps': timestamps,
        'time_slots': time_slots,
        'median_total_sendrate': median_total_sendrate,
        'settings': settings,
    }

    return scenario


def parse(paths: list[str]) -> list[dict]:
    scenarios = []
    cnt = 0
    for filepath in paths:
        # First, load the corresponding inputs file to get meta information like time slots
        inputs_json_path = filepath.replace(".out.txt", ".json")
        # try to load inputs
        inputs = None
        try:
            with open(inputs_json_path) as inputs_file:
                inputs = json.load(inputs_file)
        except:
            print(f"Could not find inputs file {inputs_json_path}")

        # Then, load the app metrics from the simulation output file
        with open(filepath) as file:
            while True:
                line = file.readline()
                if line == '':
                    break
                if "# Host Apps evaluation" in line:
                    s = parse_simulation_results(file, inputs)
                    if s:
                        scenarios.append(s)
        cnt += 1
        if cnt % 50 == 0:
            print(f"Processed {cnt} files out of {len(paths)}")
        if cnt % 1000 == 0:
            gc.collect()

    print("Processed a total of", len(scenarios), "scenarios")

    return scenarios


def main():
    global args

    args = parse_args()
    paths = []
    if os.path.isdir(args.filepath):
        for file in os.listdir(args.filepath):
            if file.endswith(".out.txt"):
                paths.append(os.path.join(args.filepath, file))
    else:
        paths.append(args.filepath)

    print(f"Found files of {len(paths)} simulations")

    if args.dark:
        dark_mode()
    if len(paths) == 1:
        scenarios = parse(paths)
        plot_single_scenario(scenarios[0])
    elif len(paths) > 1:
        cache_filename = _generate_cache_filename(paths)
        cache_filepath = os.path.join(args.filepath, cache_filename)
        if args.no_cache or not os.path.exists(cache_filepath):
            scenarios = parse(paths)
            global_results = process_multi_scenario(scenarios)
            print(f"Caching pre-processed results to {cache_filepath}")
            with open(cache_filepath, 'wb') as f:
                pickle.dump(global_results, f)

        else:
            print(f"Loading pre-processed results from cache {cache_filepath}")
            with open(cache_filepath, 'rb') as f:
                global_results = pickle.load(f)
        
        # plot_parameter_comparison(global_results)
        plot_multi_scenario(global_results)

    print("Done. Exiting.")


main()
